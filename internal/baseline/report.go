package baseline

import (
	"fmt"
	"strings"
)

// Report writes the comparison as Markdown. It is a pure function of the
// reference and the findings: the same two inputs give the same bytes, and
// nothing in it is typed by hand.
func Report(ref Reference, f Findings) string {
	rows := make([]Row, 0, len(ref.Alerts))
	for _, a := range ref.Alerts {
		rows = append(rows, Judge(a, f))
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("# Proven against Dependabot's alerts at %s\n\n", short(ref.PinnedCommit))
	w("<!-- Generated by `make baseline-dependabot` from alerts.json and proven-findings.json. Do not edit by hand. -->\n\n")
	w("evidence: %s\n\n", f.Evidence)
	w("We found these %d alerts on our own repository and turned them into a baseline for Proven. ", len(ref.Alerts))
	w("The npm alerts are real findings in `docs-site`. The Go alerts are the demo's known-exploited dependency, kept on purpose (`demo/live/README.md`). ")
	w("The comparison is made at commit `%s`, which `alerts.json` pins.\n\n", ref.PinnedCommit)

	writeCounts(&b, rows, f)
	writeRows(&b, rows, f)
	writeExtras(&b, ref, f)
	writeScope(&b, f)
	return b.String()
}

// short is the first seven digits of a commit.
func short(commit string) string {
	if len(commit) > 7 {
		return commit[:7]
	}
	return commit
}

func writeCounts(b *strings.Builder, rows []Row, f Findings) {
	count := map[Verdict]int{}
	byManifest := map[string]map[Verdict]int{}
	var manifests []string
	for _, r := range rows {
		count[r.Verdict]++
		m := r.Alert.Manifest
		if byManifest[m] == nil {
			byManifest[m] = map[Verdict]int{}
			manifests = append(manifests, m)
		}
		byManifest[m][r.Verdict]++
	}
	fmt.Fprintf(b, "## Counts\n\n")
	fmt.Fprintf(b, "run: %s\n\n", f.Mode)
	fmt.Fprintf(b, "| manifest | alerts | found | found differently | missed | not checked |\n|---|---|---|---|---|---|\n")
	for _, m := range manifests {
		c := byManifest[m]
		fmt.Fprintf(b, "| `%s` | %d | %d | %d | %d | %d |\n", m, total(c), c[Found], c[FoundDifferently], c[Missed], c[NotChecked])
	}
	fmt.Fprintf(b, "| **all** | **%d** | **%d** | **%d** | **%d** | **%d** |\n\n", len(rows), count[Found], count[FoundDifferently], count[Missed], count[NotChecked])
	if f.Mode != ModeEvidence {
		fmt.Fprintf(b, "remark: this run asked no evidence store, so no alert is found or found differently; a row is `missed` only when Proven does not read the package, and every other row is `not checked`.\n")
		fmt.Fprintf(b, "remark: `not checked` is not a miss. It says the manifest side works, and it says nothing about whether Proven would find the advisory.\n\n")
		return
	}
	fmt.Fprintf(b, "remark: `missed` after the package was read means the evidence held no row for the alert's advisory; it does not say the advisory does not exist. The evidence line names what was asked.\n")
	fmt.Fprintf(b, "remark: a KEV mark is shown only for a CVE the KEV view holds; an absent mark means not on the list only when the evidence line says the KEV view was loaded.\n\n")
}

func total(c map[Verdict]int) int {
	n := 0
	for _, v := range c {
		n += v
	}
	return n
}

func writeRows(b *strings.Builder, rows []Row, f Findings) {
	fmt.Fprintf(b, "## Alert by alert\n\n")
	fmt.Fprintf(b, "| # | package | manifest | GHSA / CVE | Dependabot range (patched) | Proven reads | read version against the range | Proven | detail | evidence |\n")
	fmt.Fprintf(b, "|---|---|---|---|---|---|---|---|---|---|\n")
	for _, r := range rows {
		a := r.Alert
		id := r.EvidenceID
		if id == "" {
			id = "no row"
		}
		fmt.Fprintf(b, "| %d | `%s` | `%s` | %s | `%s` (%s) | %s | %s | **%s** | %s | %s · %s |\n",
			a.Number, a.Package, a.Manifest, strings.Join(a.ids(), " / "), a.VulnerableRange, a.Patched,
			cell(r.Reads), cell(r.RangeCheck), r.Verdict, cell(r.Detail), id, cell(f.Evidence))
	}
	fmt.Fprintf(b, "\n")
}

func writeExtras(b *strings.Builder, ref Reference, f Findings) {
	fmt.Fprintf(b, "## What Proven found that Dependabot did not\n\n")
	if f.Mode != ModeEvidence {
		fmt.Fprintf(b, "Not checked: this run asked no evidence store.\n\n")
		return
	}
	extras := Extras(ref, f)
	if len(extras) == 0 {
		fmt.Fprintf(b, "none: every package version Proven found affected is named by an alert of the reference.\n\n")
		return
	}
	fmt.Fprintf(b, "%d package versions are affected by an advisory no alert names for that package in that file.\n\n", len(extras))
	fmt.Fprintf(b, "| manifest | package | version | advisory | aliases | KEV | evidence |\n|---|---|---|---|---|---|---|\n")
	for _, e := range extras {
		kev := "—"
		if e.KEV {
			kev = "yes"
		}
		fmt.Fprintf(b, "| `%s` | `%s` | %s | %s | %s | %s | %s · %s |\n", e.File, e.Package, e.Version, e.Advisory, cell(e.Aliases), kev, e.EvidenceID, cell(f.Evidence))
	}
	fmt.Fprintf(b, "\n")
}

func writeScope(b *strings.Builder, f Findings) {
	fmt.Fprintf(b, "## What Proven read\n\n")
	fmt.Fprintf(b, "Proven read %d package versions from %d manifest and lock files at the pinned commit, as a change from an empty base:\n\n", f.ReadsTotal, len(f.Manifests))
	for _, m := range f.Manifests {
		fmt.Fprintf(b, "- `%s`\n", m)
	}
	fmt.Fprintf(b, "\n")
}

// cell makes text safe for one Markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.ReplaceAll(s, "\n", " ")
}
