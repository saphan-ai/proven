func TestChangedAPIDocsAndTagsWithoutModel(t *testing.T) {
	base := []byte("package example\n\nfunc Unchanged() {}\n")
	head := append(append([]byte{}, base...), []byte("\n// Add adds two values.\n// @param previous stale name\nfunc Add(current int) int { return current }\n\nfunc Missing() {}\n\n// TODO: document behavior\nfunc helper() {}\n")...)
	r := Check([]change.File{{Path: "api.go", Base: base, Change: head}})
	if !r.Complete {
		t.Fatal(r.Issue)
	}
	rules := map[string]int{}
	for _, i := range r.Issues {
		rules[i.Rule]++
		if strings.Contains(i.UnitID, "Unchanged") {
			t.Fatal("flagged unchanged legacy API")
		}
	}
	if rules["missing_api_doc"] != 1 || rules["stale_param_tag"] != 1 || rules["placeholder_comment"] != 1 {
		t.Fatal(r.Issues)
	}
	if len(r.Assessments) != 0 {
		t.Fatal("invented a model assessment")
	}
}
func TestRemovedDocMalformedAndUnsupportedAreExplicit(t *testing.T) {
	r := Check([]change.File{{Path: "a.go", Base: []byte("package p\n// Run does the work.\nfunc Run() {}\n"), Change: []byte("package p\nfunc Run() {}\n")}, {Path: "x.ts", Change: []byte("export const run=()=>1;")}})
	if !r.Complete || len(r.Issues) != 1 || len(r.Unsupported) != 1 {
		t.Fatalf("%+v", r)
	}
	r = Check([]change.File{{Path: "bad.go", Change: []byte("package")}})
	if r.Complete || r.Issue == "" {
		t.Fatal("invalid Go became a clean scan")
	}
	r = Check([]change.File{{Path: "generated.go", Change: []byte("// Code generated by test. DO NOT EDIT.\npackage p\nfunc Public() {}\n")}})
	if len(r.Units) != 0 {
		t.Fatal("checked generated declarations")
	}
}

func TestRedactionPreservesEmptyArraysAndDoesNotMutateSource(t *testing.T) {
	empty := Check(nil).Redacted(func(s string) string { return s })
	if empty.Units == nil || empty.Issues == nil || empty.Assessments == nil {
		t.Fatal("required empty arrays became null")
	}
	r := Result{Units: []Unit{{ID: "unit", Text: "secret", Code: "secret", Params: []string{"secret"}}}, Issues: []Issue{{Message: "secret"}}, Assessments: []Assessment{{Reason: "secret", Quote: "secret"}}}
	copy := r.Redacted(func(s string) string { return strings.ReplaceAll(s, "secret", "[redacted]") })
	if r.Units[0].Text != "secret" || r.Units[0].Params[0] != "secret" || r.Assessments[0].Quote != "secret" {
		t.Fatal("mutated original data")
	}
	if copy.Units[0].Text != "[redacted]" || copy.Units[0].Params[0] != "[redacted]" || copy.Assessments[0].Quote != "[redacted]" {
		t.Fatal("left a sensitive field visible")
	}
}

func TestDocNamesAcceptLinksAndPunctuationWithoutAcceptingAnotherIdentifier(t *testing.T) {
	for _, text := range []string{"Run.", "Run returns a result.", "[Run] returns a result."} {
		if !startsDocName(text, "Run") {
			t.Fatal(text)
		}
	}
	for _, text := range []string{"Runner does something else.", "Run_unsafe skips checks.", "Another function."} {
		if startsDocName(text, "Run") {
			t.Fatal(text)
		}
	}
}
