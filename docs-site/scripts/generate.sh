#!/bin/sh
# Writes the generated documentation pages from the code, into the directory
# given as the one argument. Run it from any directory:
#
#   sh docs-site/scripts/generate.sh docs-site/generated
#
# The pages are never edited by hand. The image build runs this script in its Go
# stage and the stale-page guard compares the output with docs-site/generated.
set -eu

out="${1:?usage: generate.sh OUTDIR}"
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "${DOCS_REPO_ROOT:-$here/../..}" && pwd)"
module="github.com/saphan-ai/proven"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

mkdir -p "$out"
out="$(cd "$out" && pwd)"
cd "$root"

header() { # title, description
  printf -- '---\ntitle: %s\ndescription: %s\n---\n\n' "$1" "$2"
  printf '<!-- generated by docs-site/scripts/generate.sh: do not edit -->\n\n'
}

# (a) the command-line reference, from proven's own --help output
go build -o "$tmp/proven" ./cmd/proven
{
  header "Command line" "Every command and flag, from proven --help."
  printf '`proven --help` prints this page'"'"'s text. The page is written from the binary.\n\n'
  printf '## proven --help\n\n```text\n'
  "$tmp/proven" --help
  printf '```\n'
  for sub in scan ci; do
    printf '\n## proven %s --help\n\n```text\n' "$sub"
    "$tmp/proven" "$sub" --help
    printf '```\n'
  done
} >"$out/cli.md.new"
mv "$out/cli.md.new" "$out/cli.md"

# (b) the settings reference, from cmd/settings-doc: run it on a copy of the
# page in a scratch tree, so docs/ is never touched, and keep what it generated
go build -o "$tmp/settings-doc" ./cmd/settings-doc
mkdir -p "$tmp/tree/docs"
cp go.mod "$tmp/tree/go.mod"
cp docs/CONFIGURATION.md "$tmp/tree/docs/CONFIGURATION.md"
(cd "$tmp/tree" && "$tmp/settings-doc" >/dev/null)
{
  header "Settings" "Every setting, its environment variable and its default."
  sed -n '/^<!-- generated: settings -->$/,/^<!-- end generated -->$/p' "$tmp/tree/docs/CONFIGURATION.md" |
    sed '1d;$d'
} >"$out/settings.md.new"
mv "$out/settings.md.new" "$out/settings.md"

# (c) one page per adapter interface, from go doc
adapter() { # file, package, type, title, what it is
  # a relative package path resolves without the module proxy; the import
  # comment is then rewritten to the real import path
  if ! go doc "./internal/$2" "$3" >"$tmp/doc.txt" 2>"$tmp/doc.err"; then
    cat "$tmp/doc.err" >&2
    echo "generate.sh: go doc ./internal/$2 $3 failed" >&2
    exit 1
  fi
  {
    header "$4" "$5"
    printf 'This is the Go interface, with its comments, as `go doc` prints it.\n\n'
    printf '```go\n'
    sed "s|// import \"\./internal/|// import \"$module/internal/|" "$tmp/doc.txt"
    printf '```\n'
  } >"$out/$1.new"
  mv "$out/$1.new" "$out/$1"
}
adapter adapter-tool.md tool Adapter "Tool adapter" "A deterministic tool whose run is evidence."
adapter adapter-test.md testrun Adapter "Test adapter" "A language adapter that runs a test on each side."
adapter adapter-query.md query Adapter "Query adapter" "A data source queried for evidence."
adapter adapter-guardrail.md guardrail Adapter "Guardrail adapter" "A guardrail backend that judges a prompt and an answer."
adapter adapter-generator.md generator Generator "Generator" "The model that proposes a test."
adapter adapter-reviewer.md review Reviewer "Reviewer" "The reviewer a review calls."
