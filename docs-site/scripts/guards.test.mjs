// Each guard is shown to fail on exactly the input it guards, and to pass on a
// clean page. Run: npm test
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { checkConflicts, checkLinks, checkPublicText, checkStale } from './guards.mjs';
import { generatedPages } from './lib.mjs';

const page = (slug, text) => ({ slug, text });
const clean = [
  page('index', '---\ntitle: "Proven"\n---\n\nSee [the guide](/docs/guides/install#build) and [here](#top-section).\n\n## Top section\n'),
  page('guides/install', '---\ntitle: "Install"\n---\n\n## Build\n\nRun `proven --help`. Contact proven-bot@lab.local.\n'),
];

test('a clean set of pages passes every guard', () => {
  assert.deepEqual(checkLinks(clean).findings, []);
  assert.deepEqual(checkPublicText(clean), []);
  assert.deepEqual(checkConflicts(clean), []);
});

test('a link to a page that does not exist fails the links guard (negative control: the link target)', () => {
  const broken = [clean[0], page('guides/install', '## Build\n\nSee [x](/docs/guides/missing).\n')];
  const { findings } = checkLinks(broken);
  assert.equal(findings.length, 1);
  assert.match(findings[0], /guides\/install:3: \/docs\/guides\/missing: no page has that address/);
});

test('a link to a heading that does not exist fails (negative control: the anchor)', () => {
  const broken = [clean[0], page('guides/install', '## Build\n\nSee [x](/docs/guides/install#nope) and [y](#also-nope).\n')];
  assert.equal(checkLinks(broken).findings.length, 2);
});

test('a relative link left unresolved fails', () => {
  const broken = [page('index', 'See [x](../docs/GONE.md).\n')];
  assert.match(checkLinks(broken).findings[0], /not a page, an image or a file/);
});

test('a link inside a code fence is not read as a link', () => {
  assert.deepEqual(checkLinks([page('index', '```\n[x](/docs/missing)\n```\n')]).findings, []);
});

test('a fake machine name fails the public-text guard (negative control: the host name)', () => {
  const found = checkPublicText([page('guides/x', 'Run it on build-box-07.corp to try.\n')]);
  assert.equal(found.length, 1);
  assert.match(found[0], /machine name "build-box-07\.corp"/);
});

test('an internal path and a credential fail the public-text guard', () => {
  const found = checkPublicText([
    page('a', 'cd /Users/someone/work\n'),
    page('b', 'key = AKIAABCDEFGHIJKLMNOP\n'),
    page('c', 'export PROVEN_GENERATOR_KEY=nvapi-abcdefghijklmnopqrstuvwxyz0123\n'),
  ]);
  assert.deepEqual(found.map((f) => f.split(':')[0]), ['a', 'b', 'c']);
});

test('a merge-conflict marker fails the page-intact guard', () => {
  assert.equal(checkConflicts([page('guides/index', 'a\n<<<<<<< main\nb\n=======\nc\n>>>>>>> topic\n')]).length, 3);
});

test('a generated page that differs from the generator fails the stale guard (negative control: one help line)', () => {
  const dir = (body) => {
    const d = fs.mkdtempSync(path.join(os.tmpdir(), 'proven-docs-test-'));
    for (const [file] of generatedPages) fs.writeFileSync(path.join(d, file), body(file));
    return d;
  };
  const config = '<!-- generated: settings -->\nrow\n<!-- end generated -->\n';
  const settings = '---\ntitle: S\n---\n\n<!-- generated by docs-site/scripts/generate.sh: do not edit -->\n\nrow\n';
  const body = (file) => (file === 'settings.md' ? settings : `${file}\n  --severity lowest severity reported\n`);
  const same = dir(body);
  assert.deepEqual(checkStale(same, dir(body), config), []);
  const changed = dir((f) => body(f).replace('lowest severity reported', 'the least severity reported'));
  const found = checkStale(same, changed, config);
  assert.equal(found.length, generatedPages.length - 1);
  assert.match(found[0], /committed .* but the generator writes .*least severity/);
  // the page docs/CONFIGURATION.md must carry the table settings-doc writes
  assert.equal(checkStale(same, dir(body), config.replace('row', 'old row')).length, 1);
});
